def matches_for(keys):
    signals=[s for s in sig if hit(s["title"]+" "+s.get("summary",""), keys)]
    cdc=[t for t in snap.get("cdc_travel") or [] if hit(t, keys)]
    ecdc=[e for e in snap.get("ecdc") or [] if hit(e.get("title","")+" "+e.get("desc",""), keys)][:2]
