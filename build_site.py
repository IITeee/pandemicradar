def fact_line(d, signals, cdc):
    if d["slug"]=="h5n1" and snap.get("h5") and snap["h5"].get("us_cases_since_2024") is not None:
        h=snap["h5"]
        return f"CDC reports {h['us_cases_since_2024']} human H5N1 cases in the United States since 2024 and describes the risk to the public as {h.get('cdc_risk') or 'not stated'}."
    if signals:
        s=signals[0]
        return f"Latest WHO report: {s['title']} ({s['date']}), risk score {s['score']} out of 10."
    if cdc:
        return f"CDC travel notice: {cdc[0]}."
    return "No WHO Disease Outbreak News item in the last 180 days of this snapshot matched this disease."
def card_html(d, signals, cdc):
    return (f'<article class="wcard" style="--c:{d["color"]}"><h3><a href="{d["slug"]}/">{E(d["name"])}</a></h3>'
            f'<p>{E(fact_line(d, signals, cdc))}</p><a href="{d["slug"]}/">Current {E(d["name"])} status</a></article>')
def signal_html(s):
    bits=[f"Reported {s['date']}.", f"Risk score {s['score']} out of 10."]
    if s.get("cases") is not None: bits.append(f"The WHO text mentions {s['cases']:,} cases.")
    if s.get("deaths") is not None: bits.append(f"It mentions {s['deaths']:,} deaths.")
    summary=re.sub(r"\s+"," ",s.get("summary") or "").strip()
    if len(summary)>420: summary=summary[:419].rsplit(" ",1)[0]+"…"
    body=" ".join(bits)
    if summary: body+=" "+summary
    return (f'<article><h3><a href="{E(s["url"])}">{E(s["title"])}</a></h3>'
            f'<p>{E(body)} <a href="{E(s["url"])}">WHO Disease Outbreak News</a>.</p></article>')
